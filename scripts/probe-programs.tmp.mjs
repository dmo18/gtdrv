import { createRequire } from 'node:module';
import { buildGame, serve } from './build.mjs';
const { chromium } = createRequire('/opt/node-tools/node_modules/')('playwright');
await buildGame({ minify: false });
const server = await serve(0);
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 915, height: 412 }, deviceScaleFactor: 1 });
page.on('pageerror', (e) => console.log('pageerror', String(e)));
await page.goto(`http://127.0.0.1:${server.address().port}/?autostart`);
await page.waitForFunction(() => window.__rw && window.__rw.loop.running, null, { timeout: 30000 });
const r = await page.evaluate(async () => {
  const g = window.__rw, info = g.renderer.info;
  const names = () => new Set(info.programs.map((p) => p.name + ':' + p.cacheKey.slice(0, 0) + p.id));
  const log = [];
  let seen = new Set(info.programs.map((p) => p.id));
  log.push('start ' + info.programs.length);
  const mark = (label) => {
    const add = info.programs.filter((p) => !seen.has(p.id));
    add.forEach((p) => seen.add(p.id));
    log.push(label + ' +' + add.length + ' ' + add.map((p) => p.name).join(','));
  };
  const wait = (ms) => new Promise((r) => setTimeout(r, ms));
  await wait(3000); mark('3s day');
  g.daynight.setHour(19.5); await wait(2500); mark('dusk');
  g.daynight.setHour(23); await wait(2500); mark('night');
  g.daynight.setWeather('rain', true); await wait(2500); mark('rain');
  g.events.emit('explosion', { x: g.player.x + 10, y: 0, z: g.player.z, r: 6, kind: 'blast' }); await wait(2500); mark('explosion');
  g.exitVehicle(); await wait(2500); mark('foot');
  g.daynight.setHour(13); g.daynight.setWeather('clear', true); await wait(2500); mark('day again');
  return log;
});
console.log(r.join('\n'));
await browser.close(); server.close();
